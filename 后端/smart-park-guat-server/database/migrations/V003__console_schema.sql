-- 与 ConsoleService.schema 的幂等初始化一致，仅添加控制台功能表。
CREATE TABLE IF NOT EXISTS console_account (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_name VARCHAR(100) NOT NULL UNIQUE,
 display_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL,
 password_hash VARCHAR(512) NOT NULL,
 phone VARCHAR(100), email VARCHAR(200), enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS console_session (
 token_hash CHAR(64) PRIMARY KEY, account_id BIGINT NOT NULL, expires_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS console_order (
 id VARCHAR(80) PRIMARY KEY, owner_id BIGINT NULL, status VARCHAR(30) NOT NULL,
 payload LONGTEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS console_notice (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, account_id BIGINT NOT NULL,
 title VARCHAR(200) NOT NULL, content TEXT NOT NULL, order_id VARCHAR(80),
 is_read BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
